# Agregando elementos a una lista

motorcycles = ['honda', 'mortalika', 'yamaha']
print (motorcycles)

# Metodo append
motorcycles.append("kawasaki")
print (motorcycles)

"""
El metodo append ayuda a crear listas facilmente de manera
dinamica.
"""

