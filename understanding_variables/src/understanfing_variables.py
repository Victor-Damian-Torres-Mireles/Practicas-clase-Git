"""
Reglas generales para nombrar variables en PYTHON.

Los nombres de variables solo deben nombrarse con:

- Palabras en ingles.
- Letras, numeros y guion bajo.
- Deben comenzar con una letra o guion bajo, pero no con numeros.
- NO utilizar espacios para separar palabras (Utilizar _).
- NO utilizar palabras reservadas de Python o el nombre del archivo con nombre de variables.
- Los nombres deben ser cortos pero descriptivos.
- Letras minusculas, por ahora.

Ejemplo_
  correcto: message_1, _message_1
  incorrecto: 1message_1

"""

